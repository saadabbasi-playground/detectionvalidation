"""ATT&CK coverage matrix builder and Navigator layer exporter."""

from __future__ import annotations

import colorsys
from typing import Any

from detection_validator.normalizer.schema import CanonicalDetection

# Navigator layer schema version
_NAV_VERSION = "4.5"
_DOMAIN = "enterprise-attack"
_ATTCK_VERSION = "14"


def _confidence_color(confidence: float) -> str:
    """Map 0–1 confidence to a green hex color (darker = higher confidence)."""
    # hue 120° = green; lighten for low confidence, darken for high
    lightness = 0.75 - (confidence * 0.40)  # 0.75 → 0.35
    r, g, b = colorsys.hls_to_rgb(120 / 360, lightness, 0.6)
    return "#{:02x}{:02x}{:02x}".format(int(r * 255), int(g * 255), int(b * 255))


class CoverageMatrix:
    """Build a per-tactic/technique coverage matrix from a detection corpus."""

    def __init__(self, detections: list[CanonicalDetection]) -> None:
        self.detections = detections
        # {technique_id: {tactic, confidence, rule_names, rule_count}}
        self._index: dict[str, dict[str, Any]] = {}
        self._built = False

    def build(self) -> dict[str, dict[str, list[str]]]:
        """Return ``{tactic: {technique_id: [detection_names]}}``."""
        matrix: dict[str, dict[str, list[str]]] = {}
        for det in self.detections:
            for t in det.mitre_techniques:
                tid = t.full_id  # sub-technique if present, else parent
                tactic = t.tactic or "unknown"
                matrix.setdefault(tactic, {}).setdefault(tid, [])
                if det.name not in matrix[tactic][tid]:
                    matrix[tactic][tid].append(det.name)
                # Build index for Navigator export
                existing = self._index.get(tid)
                if existing is None or t.confidence > existing["confidence"]:
                    self._index[tid] = {
                        "tactic": tactic,
                        "confidence": t.confidence,
                        "rule_names": [],
                    }
                if det.name not in self._index[tid]["rule_names"]:
                    self._index[tid]["rule_names"].append(det.name)
        self._built = True
        return matrix

    def to_navigator_layer(
        self,
        name: str = "Detection Coverage",
        description: str = "Generated by detection-validator",
    ) -> dict[str, Any]:
        """Export as ATT&CK Navigator layer JSON (v4.5)."""
        if not self._built:
            self.build()

        techniques = []
        for tid, info in self._index.items():
            rule_count = len(info["rule_names"])
            comment = f"{rule_count} detection{'s' if rule_count != 1 else ''}: " + \
                      ", ".join(info["rule_names"][:5])
            if rule_count > 5:
                comment += f" (+{rule_count - 5} more)"

            techniques.append({
                "techniqueID": tid,
                "tactic": info["tactic"],
                "color": _confidence_color(info["confidence"]),
                "comment": comment,
                "enabled": True,
                "score": round(info["confidence"] * 100),
                "metadata": [
                    {"name": "rule_count", "value": str(rule_count)},
                    {"name": "confidence", "value": f"{info['confidence']:.2f}"},
                ],
                "showSubtechniques": "." in tid,
            })

        return {
            "name": name,
            "versions": {
                "attack": _ATTCK_VERSION,
                "navigator": _NAV_VERSION,
                "layer": _NAV_VERSION,
            },
            "domain": _DOMAIN,
            "description": description,
            "filters": {"platforms": [
                "Windows", "Linux", "macOS", "Cloud", "IaaS",
                "SaaS", "Office 365", "Azure AD", "Google Workspace",
            ]},
            "sorting": 3,
            "layout": {
                "layout": "side",
                "aggregateFunction": "max",
                "showID": True,
                "showName": True,
                "showAggregateScores": True,
                "countUnscored": False,
            },
            "hideDisabled": False,
            "techniques": techniques,
            "gradient": {
                "colors": ["#ffffff", "#66b366"],
                "minValue": 0,
                "maxValue": 100,
            },
            "legendItems": [
                {"label": "High confidence (≥0.8)", "color": "#2d7a2d"},
                {"label": "Medium confidence (0.6–0.8)", "color": "#4ea34e"},
                {"label": "Low confidence (<0.6)", "color": "#99cc99"},
            ],
            "metadata": [],
            "links": [],
            "showTacticRowBackground": True,
            "tacticRowBackground": "#1a1a2e",
            "selectTechniquesAcrossTactics": True,
            "selectSubtechniquesWithParent": False,
        }
